/** 指定した周回・ステージ（・場所）の生徒を返す。 */
export function getStudents(loop: number, stage: string, area?: string): Student[] {
  return STUDENTS.filter(
    (s) => s.loop === loop && s.stage === stage && (area === undefined || s.area === area),
  );
}

/** 指定した周回でチョコを持っている生徒数（撲滅率の分母）。 */
export function countChocolateHolders(loop: number, stage?: string): number {
  return STUDENTS.filter(
    (s) => s.loop === loop && (stage === undefined || s.stage === stage) && s.chocolateType !== "none",
  ).length;
}
